/**
 * Разбор текста для помощника без нейросети: нормализация, «корни» слов, числа.
 * Всё работает на русском и казахском и не требует ни интернета, ни моделей.
 */

/** Нижний регистр, ё→е, без знаков препинания (кроме цифр, пробелов и казахских букв). */
export function norm(s) {
  return String(s)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Грубый «корень» слова: отрезаем одно окончание, чтобы «чая», «чай», «чаю» сходились.
 * Короткие слова (2 буквы, например «су») не трогаем.
 */
export function stem(word) {
  let w = word;
  if (w.length > 2) {
    // Казахские окончания режем только у слов с казахскими буквами: «вода» не должна терять «да».
    const kk = /[әғқңөұүһі]/u.test(w);
    w = w.replace(kk ? /(ның|нің|дың|дің|ға|ге|қа|ке|ды|ді|ны|ні|ты|ті|да|де|та|те|ы|і)$/u : /(ами|ями|ов|ев|ом|ем|ах|ях|ы|и|а|я|у|ю|о|е|й|ь)$/u, '');
  }
  if (w.length < 2) return word;
  return w.length > 6 ? w.slice(0, 6) : w;
}

/** Корни совпали: равны, либо один начинается с другого (оба не короче 4 символов). */
export function sameStem(a, b) {
  if (a === b) return true;
  const [s, l] = a.length <= b.length ? [a, b] : [b, a];
  return s.length >= 4 && l.startsWith(s);
}

