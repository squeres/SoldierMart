/** Категории по словам запроса. */
export const CATEGORY_WORDS = {
  food: ['еда', 'еду', 'еды', 'продукт', 'поесть', 'покушать', 'питание', 'тағам', 'тамақ', 'азық'],
  hygiene: ['гигиен', 'мыться', 'умыть', 'гигиена'],
  clothing: ['одежд', 'обувь', 'одежда', 'киім', 'аяқ'],
  stationery: ['канцеляр', 'прочее', 'прочие', 'басқа', 'кеңсе'],
};

export function detectCategory(msg) {
  const ws = norm(msg).split(' ');
  for (const [cat, words] of Object.entries(CATEGORY_WORDS)) {
    if (ws.some((w) => words.some((c) => w === c || (c.length >= 5 && w.startsWith(c.slice(0, 5)))))) return cat;
  }
  return null;
}

/**
 * Сумма из фразы: «на 3000», «до 2 500 тенге», «3к», «5 тысяч».
 * @returns {number|null}
 */
export function parseBudget(msg) {
  const t = norm(msg);
  const m = /(\d[\d ]{0,9})\s*(тыс(?:яч\w*)?|к|k|мың)?(?=\s|$)/u.exec(t);
  if (!m) return null;
  const digits = m[1].replace(/\s/g, '');
  if (!digits) return null;
  let n = Number(digits);
  if (m[2]) n *= 1000;
  return Number.isFinite(n) && n >= 1 && n <= 1_000_000 ? n : null;
}

export function money(n) {
  return `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₸`;
}
