/// Результат проверки лица.
///
/// Саму проверку выполняет сервер: терминал только делает снимок и
/// отправляет его (`POST /api/face`). Решение «свой/чужой» на устройстве
/// не принимается.
enum FaceResult {
  /// Лицо совпало с эталоном этого ИИН.
  match,

  /// Лицо найдено, но это другой человек.
  noMatch,

  /// В кадре нет лица (или оно плохо видно).
  noFace,

  /// Техническая ошибка (нет связи, сбой сервера). Вход не разрешается.
  error,
}
